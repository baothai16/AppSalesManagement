/* ============================ BẢNG DỮ LIỆU ============================ */

CREATE TABLE DANHMUC (
    MADANHMUC   INT IDENTITY(1,1) PRIMARY KEY,
    TENDANHMUC  NVARCHAR(100) NOT NULL,
    MOTA        NVARCHAR(255) NULL
);
GO

CREATE TABLE SANPHAM (
    MASANPHAM   INT IDENTITY(1,1) PRIMARY KEY,
    TENSANPHAM  NVARCHAR(150) NOT NULL,
    DONGIA      DECIMAL(18,2) NOT NULL DEFAULT 0,
    SOLUONG     INT NOT NULL DEFAULT 0,
    HINHANH     NVARCHAR(255) NULL,
    MOTA        NVARCHAR(MAX) NULL,
    MADANHMUC   INT NULL,
    CONSTRAINT FK_SANPHAM_DANHMUC FOREIGN KEY (MADANHMUC) REFERENCES DANHMUC(MADANHMUC)
);
GO

CREATE TABLE TAIKHOAN (
    TENDANGNHAP NVARCHAR(50) PRIMARY KEY,
    MATKHAU     NVARCHAR(50) NOT NULL,
    HOTEN       NVARCHAR(100) NULL,
    EMAIL       NVARCHAR(100) NULL,
    DIENTHOAI   NVARCHAR(20) NULL,
    DIACHI      NVARCHAR(255) NULL,
    QUYEN       BIT NOT NULL DEFAULT 0   -- 0 = khách hàng, 1 = quản trị
);
GO

CREATE TABLE DONHANG (
    MADONHANG       INT IDENTITY(1,1) PRIMARY KEY,
    TENDANGNHAP     NVARCHAR(50) NULL,
    HOTENNGUOINHAN  NVARCHAR(100) NOT NULL,
    DIACHINHAN      NVARCHAR(255) NOT NULL,
    DIENTHOAINHAN   NVARCHAR(20) NOT NULL,
    NGAYDAT         DATETIME NOT NULL DEFAULT GETDATE(),
    TONGTIEN        DECIMAL(18,2) NOT NULL DEFAULT 0,
    TRANGTHAI       NVARCHAR(50) NOT NULL DEFAULT N'Chờ xử lý',
    CONSTRAINT FK_DONHANG_TAIKHOAN FOREIGN KEY (TENDANGNHAP) REFERENCES TAIKHOAN(TENDANGNHAP)
);
GO

CREATE TABLE CTDONHANG (
    MADONHANG   INT NOT NULL,
    MASANPHAM   INT NOT NULL,
    TENSANPHAM  NVARCHAR(150) NOT NULL,
    SOLUONG     INT NOT NULL,
    DONGIA      DECIMAL(18,2) NOT NULL,
    CONSTRAINT PK_CTDONHANG PRIMARY KEY (MADONHANG, MASANPHAM),
    CONSTRAINT FK_CTDONHANG_DONHANG FOREIGN KEY (MADONHANG) REFERENCES DONHANG(MADONHANG)
);
GO

