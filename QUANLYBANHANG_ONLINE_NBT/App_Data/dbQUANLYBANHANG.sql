-- ===== DANH MỤC =====
CREATE OR ALTER PROCEDURE psGetTableDANHMUC
    @MADANHMUC INT = NULL
AS
BEGIN
    IF @MADANHMUC IS NULL
        SELECT * FROM DANHMUC ORDER BY TENDANHMUC;
    ELSE
        SELECT * FROM DANHMUC WHERE MADANHMUC = @MADANHMUC;
END
GO

CREATE OR ALTER PROCEDURE psInsertRecordDANHMUC
    @TENDANHMUC NVARCHAR(100),
    @MOTA NVARCHAR(255) = NULL
AS
BEGIN
    INSERT INTO DANHMUC(TENDANHMUC, MOTA) VALUES(@TENDANHMUC, @MOTA);
END
GO

CREATE OR ALTER PROCEDURE psUpdateRecordDANHMUC
    @MADANHMUC INT,
    @TENDANHMUC NVARCHAR(100),
    @MOTA NVARCHAR(255) = NULL
AS
BEGIN
    UPDATE DANHMUC SET TENDANHMUC = @TENDANHMUC, MOTA = @MOTA WHERE MADANHMUC = @MADANHMUC;
END
GO

CREATE OR ALTER PROCEDURE psDeleteRecordDANHMUC
    @MADANHMUC INT
AS
BEGIN
    DELETE FROM DANHMUC WHERE MADANHMUC = @MADANHMUC;
END
GO

-- ===== SẢN PHẨM =====
CREATE OR ALTER PROCEDURE psGetTableSANPHAM
    @MASANPHAM INT = NULL
AS
BEGIN
    IF @MASANPHAM IS NULL
        SELECT * FROM SANPHAM ORDER BY MASANPHAM DESC;
    ELSE
        SELECT * FROM SANPHAM WHERE MASANPHAM = @MASANPHAM;
END
GO

CREATE OR ALTER PROCEDURE psGetTableSanPhamTheoDanhMuc
    @MADANHMUC INT
AS
BEGIN
    SELECT * FROM SANPHAM WHERE MADANHMUC = @MADANHMUC ORDER BY MASANPHAM DESC;
END
GO

CREATE OR ALTER PROCEDURE psInsertRecordSANPHAM
    @TENSANPHAM NVARCHAR(150),
    @DONGIA DECIMAL(18,2),
    @SOLUONG INT,
    @HINHANH NVARCHAR(255) = NULL,
    @MOTA NVARCHAR(MAX) = NULL,
    @MADANHMUC INT = NULL
AS
BEGIN
    INSERT INTO SANPHAM(TENSANPHAM, DONGIA, SOLUONG, HINHANH, MOTA, MADANHMUC)
    VALUES(@TENSANPHAM, @DONGIA, @SOLUONG, @HINHANH, @MOTA, @MADANHMUC);
END
GO

CREATE OR ALTER PROCEDURE psUpdateRecordSANPHAM
    @MASANPHAM INT,
    @TENSANPHAM NVARCHAR(150),
    @DONGIA DECIMAL(18,2),
    @SOLUONG INT,
    @HINHANH NVARCHAR(255) = NULL,
    @MOTA NVARCHAR(MAX) = NULL,
    @MADANHMUC INT = NULL
AS
BEGIN
    UPDATE SANPHAM SET
        TENSANPHAM = @TENSANPHAM,
        DONGIA = @DONGIA,
        SOLUONG = @SOLUONG,
        HINHANH = ISNULL(@HINHANH, HINHANH),
        MOTA = @MOTA,
        MADANHMUC = @MADANHMUC
    WHERE MASANPHAM = @MASANPHAM;
END
GO

CREATE OR ALTER PROCEDURE psDeleteRecordSANPHAM
    @MASANPHAM INT
AS
BEGIN
    DELETE FROM SANPHAM WHERE MASANPHAM = @MASANPHAM;
END
GO

CREATE OR ALTER PROCEDURE psTimKiemSanPham
    @TUKHOA NVARCHAR(150)
AS
BEGIN
    SELECT * FROM SANPHAM WHERE TENSANPHAM LIKE '%' + @TUKHOA + '%' ORDER BY MASANPHAM DESC;
END
GO

